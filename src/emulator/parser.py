"""Разбор строки ввода на команду и аргументы."""

BYTE_ORDER_MARK = "﻿"


def parse_line(line):
    """Разделить строку на команду и аргументы по пробелам.

    Возвращает список слов: первый элемент — имя команды,
    остальные — её аргументы. Пустая строка даёт пустой список.
    Метка порядка байтов (BOM), которую добавляют некоторые
    терминалы при передаче ввода через конвейер, отбрасывается.
    """
    return line.replace(BYTE_ORDER_MARK, "").split()
